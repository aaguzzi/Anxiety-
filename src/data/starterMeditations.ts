import { Meditation } from '../types';

// Writing rules for these scripts, because a synthetic voice reads them:
// - full sentences, one per line where possible (very short fragments are spoken unclearly)
// - no words whose pronunciation depends on meaning (live, lead, tear, bow, "close" meaning near)
// - numbers as words, no abbreviations

type Line = [text: string, pause: number];

export const STARTER_GROUPS = ['For right now', 'Thoughts and feelings', 'Morning and night', 'Longer practice'] as const;
export type StarterGroup = (typeof STARTER_GROUPS)[number];

export interface StarterMeditation extends Meditation {
  group: StarterGroup;
}

function starter(id: string, group: StarterGroup, title: string, prompt: string, minutes: number, lines: Line[]): StarterMeditation {
  return {
    id,
    group,
    title,
    prompt,
    minutes,
    createdAt: '2026-01-01T00:00:00.000Z',
    segments: lines.map(([text, pause]) => ({ text, pause })),
  };
}

